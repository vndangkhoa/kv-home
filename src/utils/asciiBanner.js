/**
 * Render ASCII text banner using a specific font style
 * @param {string} text - The input text to render (e.g. "KV HOME")
 * @param {string} fontId - Font identifier ('ansi_shadow' | 'slant' | 'standard' | 'small_block' | 'cyber' | 'doom' | 'mini')
 * @param {string} [customRaw] - Optional raw ASCII string override
 * @returns {string} Multiline ASCII banner string
 */
export function renderAsciiBanner(text = 'KV HOME', fontId = 'ansi_shadow', customRaw = '') {
  // If custom raw ASCII art is provided, return it directly
  if (customRaw && typeof customRaw === 'string' && customRaw.trim().length > 0) {
    return customRaw.trimEnd();
  }

  const cleanText = (text && typeof text === 'string' && text.trim().length > 0) ? text.trim() : 'KV HOME';
  const targetFont = FONT_MAP[fontId] || FONT_MAP['ansi_shadow'];
  const { height, chars } = targetFont;

  const lines = Array(height).fill('');
  const upper = cleanText.toUpperCase();

  for (let c = 0; c < upper.length; c++) {
    const ch = upper[c];
    let glyph = chars[ch];

    // Fallback if character not in font
    if (!glyph) {
      if (ch === ' ') glyph = chars[' '];
      else glyph = chars['?'] || chars[' '] || Array(height).fill(' ');
    }

    for (let row = 0; row < height; row++) {
      lines[row] += (glyph[row] !== undefined ? glyph[row] : ' ') + (fontId === 'small_block' ? '' : ' ');
    }
  }

  // Remove trailing empty rows if any
  return lines.join('\n').trimEnd();
}
